package ca.ualberta.odobot.guidance.connectionmanagers;

import ca.ualberta.odobot.guidance.Channel;
import ca.ualberta.odobot.guidance.ChannelConnection;
import ca.ualberta.odobot.guidance.InstructionDispatcher;
import ca.ualberta.odobot.guidance.OdoClient;
import ca.ualberta.odobot.guidance.feedback.AlternateXpath;
import ca.ualberta.odobot.guidance.feedback.UnresolvableXpath;
import io.vertx.core.Context;
import io.vertx.core.Future;
import io.vertx.core.Vertx;
import io.vertx.core.json.JsonObject;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * The guidance channel: instructions for the page and the page's feedback, which OdoX's background passes to and from
 * the page. The channel is open only while OdoX has a page ready (PAGE_READY), and every message is addressed to a page
 * by its {@code pageId}.
 *
 * <p>The channel never holds messages. When an instruction goes out is decided by the {@link InstructionDispatcher},
 * which waits for a page; this manager only carries it. A message sent while no page is ready is dropped, and a request
 * among them fails.</p>
 */
public class GuidanceConnectionManager extends AbstractConnectionManager implements ConnectionManager {

    private static final Logger log = LoggerFactory.getLogger(GuidanceConnectionManager.class);
    private static final String SOURCE = "GuidanceConnectionManager";

    /**
     * The context this socket's messages are handled on. Agent logic runs on it as well.
     */
    private Context context = null;

    public GuidanceConnectionManager(OdoClient client){
        super(client, Channel.GUIDANCE);
    }

    @Override
    public void updateConnection(ChannelConnection connection) {
        super.updateConnection(connection);
        context = Vertx.currentContext();
    }

    /**
     * @return the context OdoX's socket was bound on, which runs the agent, or null before OdoX has connected.
     */
    public Context context(){
        return context;
    }

    /**
     * Replies (EXECUTE_DONE, EXECUTION_RESULT, NAVIGATION_OPTIONS_SHOW_RESULT, CLEAR_NAVIGATION_OPTIONS_RESULT) complete
     * their request; they are recorded in the history here.
     */
    @Override
    protected void onReply(JsonObject message) {
        super.addHistory(message);
    }

    /**
     * NOT_DELIVERED answers a message OdoX could not deliver, because the page it was addressed to had gone. The
     * dispatcher decides what happens to an instruction; any other request among them fails.
     */
    @Override
    public void dispatch(JsonObject message) {
        if("NOT_DELIVERED".equals(message.getString("type"))){
            super.addHistory(message);
            if(!client.getRequestManager().getDispatcher().onNotDelivered(message)){
                failReply(message.getString("replyTo"), "OdoX could not deliver it: " + message.getString("reason"));
            }
            return;
        }
        super.dispatch(message);
    }

    public void onMessage(JsonObject message){
        switch (message.getString("type")){
            case "PAGE_READY":
                super.addHistory(message);
                String pageId = message.getString("pageId");
                if(pageId == null){
                    log.warn("Ignoring a PAGE_READY without a pageId.");
                    break;
                }
                client.onPageReady(pageId);
                break;
            case "PAGE_GONE":
                super.addHistory(message);
                client.onPageGone(message.getString("pageId"));
                break;

            case "UNRESOLVABLE_XPATH":
                log.info("OdoX reported unresolvable xpath: {} from instruction generated by path node: {}. Attempting to back-track and recover.", message.getString("xpath"), message.getString("sourceNodeId"));
                var failedNodeId = message.getString("sourceNodeId");

                log.info("{}", message.encodePrettily());
                super.addHistory(message);
                client.getRequestManager().onObservation(new UnresolvableXpath(message.getString("xpath"), failedNodeId));


                break;
            case "REGISTER_ALTERNATE_XPATH":
                //During the execution of certain instructions, the exact xpath sent to OdoX by the server might differ from the one OdoX had to use to actually execute the instruction.
                //When this happens, the agent adds the new xpath OdoX used to the corresponding instruction so that it can properly identify that the expected instruciton was executed.
                //TODO: eventually, these new xpaths should be merged into the nav model.
                String alternateXpath = message.getString("alternateXpath");
                String sourceNodeId = message.getString("sourceNodeId");

                log.info("OdoX reported alternate xpath: {} for sourceNodeId: {}", alternateXpath, sourceNodeId);
                client.getRequestManager().onObservation(new AlternateXpath(alternateXpath, sourceNodeId));

                super.addHistory(message);

                //The page that asked is waiting for the confirmation, so it goes straight to that page.
                JsonObject confirmation = new JsonObject()
                        .put("type", "ALTERNATE_XPATH_CONFIRMED")
                        .put("replyTo", message.getString("id"))
                        .put("pageId", message.getString("pageId"))
                        .put("source", SOURCE)
                        .put("pathsRequestId", client.getRequestManager().getExecutionId().toString())
                        .put("alternateXpath", alternateXpath); //Confirm which xpath was registered.
                send(confirmation);

                break;
            default:
                log.warn("Unexpected message of type {} on the guidance channel.", message.getString("type"));
        }
    }

    public Future<JsonObject> clearNavigationOptions(){
        JsonObject clearNavigationOptionsRequest = new JsonObject()
                .put("type", "CLEAR_NAVIGATION_OPTIONS")
                .put("source", SOURCE)
                .put("pathsRequestId", client.getRequestManager().getExecutionId().toString());

        Future<JsonObject> reply = expectReply(clearNavigationOptionsRequest);
        client.getRequestManager().getDispatcher().send(clearNavigationOptionsRequest);
        return reply;
    }

    public Future<JsonObject> showNavigationOptions(JsonObject navigationOptions){
        JsonObject showNavigationOptionsRequest = new JsonObject()
                .put("type", "SHOW_NAVIGATION_OPTIONS")
                .put("source", SOURCE)
                .put("pathsRequestId", client.getRequestManager().getExecutionId().toString())
                .mergeIn(navigationOptions);

        Future<JsonObject> reply = expectReply(showNavigationOptionsRequest);
        InstructionDispatcher dispatcher = client.getRequestManager().getDispatcher();
        dispatcher.afterPause(dispatcher.policy().followUpPause(), ()->dispatcher.send(showNavigationOptionsRequest));

        return reply;
    }

    /**
     * @return whether a message sent now would go out: the socket is connected and a page is ready.
     */
    public boolean canSend(){
        return isOpen();
    }

    /**
     * Wait for OdoX's reply to an EXECUTE message the dispatcher sends later: EXECUTE_DONE, or EXECUTION_RESULT for a
     * multi-step instruction.
     * @return completes with the reply.
     */
    public Future<JsonObject> expectReplyTo(JsonObject executionRequest){
        return expectReply(executionRequest);
    }

    /**
     * Send an EXECUTE message the dispatcher has released to the page it is addressed to.
     */
    public boolean sendExecute(JsonObject executionRequest){
        return sendQueued(executionRequest);
    }

    /**
     * Send a message the dispatcher has released from its queue, see {@link InstructionDispatcher#send}.
     */
    public boolean sendQueued(JsonObject message){
        super.addHistory(message);
        return sendOrFail(message);
    }

    /**
     * Send a reply to the page that asked, e.g. ALTERNATE_XPATH_CONFIRMED, without waiting in the dispatcher's queue.
     * Messages OdoBot starts go through {@link InstructionDispatcher#send} instead.
     */
    protected boolean send(JsonObject data){
        data.put("delayed", false);
        super.addHistory(data);
        return sendOrFail(data);
    }

    /**
     * Send a message now, or drop it if no page is ready, failing the request among them.
     */
    private boolean sendOrFail(JsonObject message){
        if(super.send(message)){
            return true;
        }
        failReply(message.getString("id"), "No page was ready to receive it");
        return false;
    }

    /**
     * The guidance channel never holds a message: the dispatcher waits for a page instead. One sent while no page is
     * ready is dropped.
     */
    @Override
    protected boolean send(String data){
        if(!isOpen()){
            log.warn("No page is ready, dropping a guidance message: {}", data.substring(0, Math.min(data.length(), 150)));
            return false;
        }
        return super.send(data);
    }

    /**
     * Tells the dispatcher when an EXECUTE message has actually gone to OdoX.
     */
    @Override
    protected void onSent(String data){
        if(!data.contains("\"EXECUTE\"")){
            return;
        }
        JsonObject message = new JsonObject(data);
        if("EXECUTE".equals(message.getString("type"))){
            client.getRequestManager().getDispatcher().onExecuteSent(message);
        }
    }

    public void dumpHistory(){
        super.saveHistory(SOURCE);
        super.history.clear();
    }

}
